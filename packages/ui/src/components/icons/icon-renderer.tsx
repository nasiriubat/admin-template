export const registeredIconNames = Object.keys(iconMap);

export interface IconRendererProps extends LucideProps {
  name: string;
}

/** Decorative by default (aria-hidden); pass `aria-label` for meaningful standalone icons. */
export function IconRenderer({ name, className = 'size-5', ...props }: IconRendererProps) {
  const Icon = iconMap[name] ?? HelpCircle;
  const decorative = !props['aria-label'];
  return <Icon className={className} aria-hidden={decorative ? true : undefined} {...props} />;
}
